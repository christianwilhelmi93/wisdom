"""Build precomputed multiple-choice distractors for every card -> ../mc.js
For each card and each question kind we pick 3 distractors from OTHER books that are topically close
(TF-IDF cosine on insight+question+answer), but not near-duplicates, similar length, and preferably the same
grammatical opening, so wrong options sound right and can't be eliminated by keyword/length/grammar.
Kinds: A = answer to the card question, X = 'apply it' action, T = the idea (first sentence of insight)."""
import json,re,math,collections
src=open('../cards.js').read();C=json.loads(src[src.index('['):src.index('];')+1])
STOP=set("the a an of to and in is it that you your for on with as be are by or this not at what why how does do from per his her their they we i our more most than into can if when which who one".split())
tok=lambda s:[w for w in re.findall(r"[a-z']+",s.lower()) if w not in STOP and len(w)>2]
first=lambda s:re.split(r'(?<=[.!?])\s',s)[0]
docs=[tok(c[4]+' '+c[5]+' '+c[6]) for c in C];df=collections.Counter(w for d in docs for w in set(d));N=len(C)
vec=[];
for d in docs:
  tf=collections.Counter(d);v={w:(1+math.log(n))*math.log(N/df[w]) for w,n in tf.items()};nn=math.sqrt(sum(x*x for x in v.values())) or 1;vec.append({w:x/nn for w,x in v.items()})
def cos(a,b):
  if len(a)>len(b):a,b=b,a
  return sum(x*b.get(w,0) for w,x in a.items())
norm=lambda s:re.sub(r'[^a-z ]','',s.lower()).strip()
def pick(i,field,cap=0.55,ovc=0.5):
  c=C[i];own=field(c);L=len(own);fw=(own.split()[:1] or [''])[0].lower();ownw=set(tok(own))
  cands=[]
  for j,d in enumerate(C):
    if j==i or d[3]==c[3] or d[2]==c[2]:continue          # other book AND other author
    opt=field(d)
    if norm(opt)==norm(own):continue
    s=cos(vec[i],vec[j])
    if s>cap:continue                                     # near duplicate idea -> could also be right
    ov=len(ownw&set(tok(opt)))/max(1,len(ownw))
    if ov>ovc:continue                                     # too many shared words -> ambiguous
    lr=len(opt)/max(1,L)
    qw=lambda q:' '.join(q.lower().split()[:2]);score=s+(0.12 if d[0]==c[0] else 0)+(0.07 if field(c)==c[6] and qw(d[5])==qw(c[5]) else 0.03 if field(c)==c[6] and d[5].split()[0].lower()==c[5].split()[0].lower() else 0)+(0.15 if (opt.split()[:1] or [''])[0].lower()==fw else 0)-0.25*abs(math.log(max(lr,.05)))
    cands.append((score,j))
  cands.sort(reverse=True);out=[];seen=set()
  for _,j in cands:
    k=norm(field(C[j]))
    if k in seen:continue
    seen.add(k);out.append(j)
    if len(out)==3:break
  return out
A=[pick(i,lambda c:c[6]) for i in range(N)]
X=[pick(i,lambda c:c[7],0.3,0.25) for i in range(N)]
T=[pick(i,lambda c:first(c[4]),0.35,0.34) for i in range(N)]
open('../mc.js','w').write('// Generated by content/build_mc.py: per card, 3 distractor card indices for A=answer, X=action, T=idea\nconst MC_A='+json.dumps(A,separators=(',',':'))+';\nconst MC_X='+json.dumps(X,separators=(',',':'))+';\nconst MC_T='+json.dumps(T,separators=(',',':'))+';\n')
for i in (0,500,503,900,[i for i,c in enumerate(C) if c[4].startswith('Cooperate with the inev')][0]):
  c=C[i];print('\nQ:',c[5],'\n  *',c[6]);[print('   ',C[j][6],'—',C[j][2]) for j in A[i]]
  print(' APPLY idea:',first(c[4]),'\n  *',c[7]);[print('   ',C[j][7]) for j in X[i]]
